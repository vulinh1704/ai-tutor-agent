export const messages: Record<Language, Record<MessageKey, string>> = { en, vi };

export const LANGUAGES: readonly Language[] = ["en", "vi"];

/** Vietnamese for any `vi` or `vi-*` browser language, English otherwise. */
export function detectLanguage(preferred: readonly string[]): Language {
  const first = preferred.find(Boolean)?.toLowerCase() ?? "";
  return first === "vi" || first.startsWith("vi-") ? "vi" : "en";
}

/** Look up `key` in `language` and fill in `{placeholders}`. */
export function translate(
  language: Language,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const template = messages[language][key] ?? en[key];
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}
